QUÉ PODÉS HACER EN AQUELLAS LUNAS
Aquellas Lunas reúne información astronómica y meteorológica para ayudarte a entender qué está pasando en el cielo, qué podés ver desde tu ubicación y cuándo conviene observar o fotografiar.
El sitio está pensado para público general. La idea es mostrar primero lo más importante con un lenguaje claro y accesible, y ofrecer información más técnica cuando quieras profundizar.
EL CIELO HOY
Esta sección resume la jornada completa del Sol y la Luna para la ubicación elegida.
Podés consultar:
la fase y el porcentaje iluminado de la Luna;
la hora de salida y puesta de la Luna;
la hora de salida y puesta del Sol;
si la Luna está sobre el horizonte;
su altura y dirección;
los intervalos durante los que será visible;
la duración del día;
los distintos crepúsculos;
la hora azul;
la hora dorada;
la nubosidad prevista;
los mejores momentos para observar.
Los gráficos permiten ver cómo cambia la altura del Sol y la Luna a lo largo del día. También muestran los períodos de día, noche y crepúsculo para entender mejor en qué momento se produce cada salida, puesta o evento.
Cuando existe información meteorológica disponible, se incluye la previsión de nubosidad y el detalle de la altura de las nubes.
EL CIELO ESTA NOCHE
Esta sección está pensada para responder una pregunta simple: qué vale la pena mirar esta noche.
La información se adapta al momento de la consulta. Si todavía es de día, muestra la próxima noche. Si ya oscureció, se concentra en lo que continúa visible o aparecerá más tarde.
Podés encontrar:
planetas visibles;
estrellas destacadas;
conjunciones;
otros objetos de interés;
horarios aproximados;
dirección hacia la que conviene mirar;
tiempo durante el que permanecerán visibles;
tipo de ayuda óptica recomendada;
nubosidad prevista durante la noche.
No busca enumerar todos los objetos posibles, sino destacar los más interesantes y presentar la información de una manera práctica.
CALENDARIO SOLAR Y LUNAR
El Calendario solar y lunar permite comparar varios días y planificar con anticipación.
Para cada fecha muestra:
salida y puesta del Sol;
salida y puesta de la Luna;
fase lunar;
porcentaje iluminado;
edad de la Luna;
duración del día;
intervalos de visibilidad;
recorrido horario del Sol y la Luna.
Las barras de visibilidad permiten reconocer rápidamente en qué momentos del día la Luna estará sobre el horizonte.
Esta sección es especialmente útil para comparar fechas cercanas y elegir el mejor día para una observación o una fotografía.
EVENTOS LUNARES
Eventos lunares reúne los principales acontecimientos relacionados con la Luna.
Entre ellos pueden aparecer:
Luna nueva;
cuarto creciente;
Luna llena;
cuarto menguante;
conjunciones con planetas, estrellas o cúmulos;
perigeos y apogeos;
libraciones;
luz cenicienta;
Lunas muy finas antes o después de Luna nueva;
eclipses;
oportunidades en las que la Luna llena coincide de manera cercana con la salida o puesta del Sol.
Cada evento se calcula para la ubicación seleccionada y puede incluir información como:
fecha y hora local;
visibilidad;
posición en el cielo;
separación angular;
porcentaje iluminado;
horarios de salida o puesta;
nubosidad prevista;
recomendaciones breves para observar o fotografiar.
Cuando un evento tiene más información disponible, se puede abrir un detalle técnico con datos adicionales.
ECLIPSES
La sección Eclipses permite consultar eclipses solares y lunares, tanto próximos como de otros años.
Para cada eclipse se puede ver:
fecha y hora local;
tipo de eclipse;
si será visible desde la ubicación elegida;
inicio, máximo y final del fenómeno;
magnitud;
altura sobre el horizonte;
mapa de visibilidad, cuando está disponible;
observaciones específicas para la ubicación.
Que un eclipse ocurra no significa que pueda verse desde cualquier lugar. Por eso la web diferencia entre el evento global y su visibilidad local.
Los eclipses que aparecen en Eventos lunares pueden abrir el mismo detalle completo disponible en esta sección.
PLANIFICADOR
El Planificador está orientado a quienes quieren preparar una observación o una fotografía con mayor precisión.
Permite consultar:
posición del Sol y la Luna;
azimut;
altura;
dirección;
horarios de salida y puesta;
trayectoria sobre el horizonte;
posición para una fecha y hora determinada.
Puede servir para anticipar dónde aparecerá la Luna, comparar horarios o preparar una composición con edificios, paisajes u otros elementos del entorno.
TU UBICACIÓN
Los horarios y resultados cambian según el lugar desde el que observás.
La ubicación elegida influye en:
la salida y puesta del Sol;
la salida y puesta de la Luna;
la dirección y altura de los astros;
los períodos de visibilidad;
la duración del día;
los crepúsculos;
la visibilidad de eclipses;
la previsión meteorológica.
Podés seleccionar otra ubicación para consultar cómo se verá el cielo desde allí.
La fecha, la hora y la zona horaria mostradas se adaptan a esa ubicación.
CÁLCULOS ASTRONÓMICOS PROPIOS
La información de la web no proviene de una tabla fija preparada para una única ciudad.
Los datos astronómicos se calculan para la fecha y ubicación seleccionadas.
Entre esos cálculos se encuentran:
posición del Sol y la Luna;
altura y azimut;
salidas y puestas;
fases;
iluminación;
visibilidad;
crepúsculos;
conjunciones;
libraciones;
perigeos y apogeos;
eclipses;
trayectorias.
Estos cálculos se combinan con información meteorológica para ofrecer una visión más útil de las condiciones reales de observación.
PREVISIÓN DEL CIELO
Cuando hay pronóstico disponible, la web incorpora datos meteorológicos para ayudar a evaluar si un evento podrá observarse.
Puede mostrar:
porcentaje de nubosidad;
estado general del cielo;
nubosidad por hora;
altura de las distintas capas de nubes;
momento con mejores condiciones previstas.
La previsión meteorológica es orientativa y puede cambiar. Su función es ayudar a decidir cuándo puede valer la pena observar, no garantizar que el cielo estará despejado.
INFORMACIÓN SIMPLE Y DETALLE TÉCNICO
La primera capa de información intenta responder preguntas directas:
qué ocurre;
cuándo ocurre;
hacia dónde mirar;
si está visible;
cuánto tiempo queda;
si las condiciones parecen favorables.
Cuando querés profundizar, algunas tarjetas incluyen un enlace a Datos técnicos o Ver detalles.
Según el evento, allí pueden aparecer:
horarios completos;
ángulos;
alturas;
azimut;
separaciones angulares;
intervalos de visibilidad;
contactos de un eclipse;
magnitud;
distancias;
datos meteorológicos;
mapas.
De esta manera, la información principal sigue siendo clara, pero los datos más precisos continúan disponibles.
AGENDAR EVENTOS
Los eventos que tienen una fecha y una hora confiables pueden agregarse a un calendario.
La opción Agendar evento permite abrir el evento ya preparado en:
Google Calendar;
Outlook;
Apple Calendar;
otros calendarios compatibles.
El evento puede incluir:
título;
fecha y hora;
duración;
descripción;
ubicación;
zona horaria;
enlace a la web.
La aplicación de calendario siempre solicita una confirmación antes de guardarlo.
