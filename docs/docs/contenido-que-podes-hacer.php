Según el dispositivo, es posible:
instalarla como una aplicación en Android;
agregarla a la pantalla de inicio en iPhone o iPad;
instalarla como aplicación en una computadora compatible;
guardarla en los favoritos del navegador.
La versión instalada sigue siendo la misma web. Cuando el sitio se actualiza, las nuevas funciones y contenidos también quedan disponibles.
UNA WEB PARA ENTENDER Y DISFRUTAR EL CIELO
Aquellas Lunas no busca mostrar todos los datos posibles ni reemplazar una formación astronómica.
Su objetivo es ayudarte a entender qué está pasando en el cielo, saber cuándo conviene mirar y descubrir eventos que pueden pasar inadvertidos.
La información técnica está disponible, pero la prioridad es que cualquier persona pueda orientarse, observar y disfrutar el cielo sin necesidad de conocimientos previos.